    private void chkChIdActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_chkChIdActionPerformed
        boolean b = chkChId.isSelected();
        txtMacChId.setEnabled(b);
        txtMacChId.setEditable(b);
        if (!b) txtMacChId.setText("");
    }//GEN-LAST:event_chkChIdActionPerformed

    private void txtMacChIdKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtMacChIdKeyTyped
        if (txtMacChId.getText().length() >= 4) {
            evt.consume();
        } else {
            String c = String.valueOf(evt.getKeyChar());
            if (Shared.isHex(c)) {
                evt.setKeyChar(c.toUpperCase(Locale.ENGLISH).toCharArray()[0]);
            } else {
                evt.consume();
            }
        }
    }//GEN-LAST:event_txtMacChIdKeyTyped

    private void btnOKActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnOKActionPerformed
        String chid = checkMacChId(txtMacChId.getText());
        if (chid == null) return;
        settings = new MacSettings(
                chid,
                chkAudioMode.isSelected(),
                chkAudioQuality.isSelected(),
                chkAudioCompression.isSelected(),
                chkAudioProtection.isSelected()
        );
        this.dispose();
    }//GEN-LAST:event_btnOKActionPerformed

