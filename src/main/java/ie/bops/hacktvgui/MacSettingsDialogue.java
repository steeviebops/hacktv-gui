    public void postInit() {
        if (settings == null) return;
        String chid = settings.channelID();
        if (chid == null || chid.isBlank()) {
            if (chkChId.isSelected()) chkChId.doClick();
        } else {
            if (!chkChId.isSelected()) chkChId.doClick();
            txtMacChId.setText(chid);
        }
        chkAudioMode.setSelected(settings.audioMode());
        chkAudioQuality.setSelected(settings.audioQuality());
        chkAudioCompression.setSelected(settings.audioCompression());
        chkAudioProtection.setSelected(settings.audioProtection());
    }
    
    private String checkMacChId(String input) {
        if (chkChId.isSelected()) {
            if (Shared.isHex(input)) {
                return input;
            } else {
                Shared.messageBox("Please specify a valid hexadecimal channel ID.", JOptionPane.WARNING_MESSAGE);
                return null;
            }
        } else {
            // Return an empty string because null is indicative of an error condition
            return "";
        }
    }
    
    public MacSettings getSettings() {
        return settings;
    }
    
